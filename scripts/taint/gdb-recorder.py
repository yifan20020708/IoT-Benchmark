#!/usr/bin/env python3
"""gdb-recorder — the GDB-side stop-read-compare engine for verify-request.sh.

Driven entirely by environment variables (set by the driver):
  VPROBE_SPEC        normalized probe spec (see verify-request.sh header)
  VPROBE_LOG         JSONL event log path (appended; flushed per event)
  VPROBE_BRIDGE      <container-bridge-ip> to reach QEMU's gdbstub on :1234
  VPROBE_CANARIES    JSON {probe_id: {"string": s, "int": n}} — generated by
                     the driver; the agent never knows these values
  VPROBE_ARM_MARKER  optional path — DEFERRED ARMING: the guest boots at
                     NATIVE speed with zero breakpoints (QEMU's -s -S leaves
                     the CPU frozen; the recorder's first `continue` releases
                     it). When the driver has confirmed the web service
                     answers it touches the marker file and SIGINTs this gdb
                     process: `continue` returns, the marker is seen, ALL
                     breakpoints are armed, and the send phase runs fully
                     instrumented. Canaries only exist after the first send,
                     so nothing observable is lost — what IS lost is the
                     boot-phase breakpoint grind that starves the guest.
  VPROBE_HIT_BUDGET  per-breakpoint canary-less stop budget (default 2000;
                     0 disables). A stop that matches no canary of ANY probe
                     costs a gdb round-trip that briefly freezes the VM; a
                     site whose stops keep matching nothing (a guest
                     self-poll, a handler loop) trips the budget and is
                     disabled (logged as `site_disabled`). A stop that DOES
                     carry a canary resets the counter.
  VPROBE_HIT_RATE    burst rule: a site whose last N (default 40) canary-less
                     stops all landed within 2 seconds is a loop — disable
                     immediately (0 disables).
  VPROBE_READSZ      bytes read per location (default 512).

A PURE FRAMEWORK. This recorder has ZERO firmware knowledge: no symbol
files (it never loads one — the architecture comes from QEMU's gdbstub
target description), no ABI register tables, no call-site/return-site
arithmetic, no notion of what a "source" or "getter" is. Every breakpoint
address and every read location comes from the spec; the recorder stops,
reads, compares, logs, auto-continues. The host-side driver owns all
timing (web wait, arm handshake, request sends, teardown, kill).

Checks of the same probe at the same address are merged into ONE
breakpoint with the union of their read locations (an agent may split one
stop into several checks; the budget must not burn N-times for it).

Event kinds (one JSON object per line, each with a unix timestamp):
  armed         breakpoints armed (phase: "boot" | "send-start"), counts,
                budget config
  check_stop    a breakpoint was hit: probe, break address, the value and
                printable string at every read location, the canary
                interpretations that matched, foreign-probe canary
                sightings (contamination diagnostics — never a pass)
  site_disabled a breakpoint tripped its canary-less budget and was
                disabled — later silence at that site is explained by this
                event, not by the target going quiet
  bp_error      a breakpoint failed to arm (the run continues without it)
  error         internal recorder error (never fatal to the session)
  deferred / stray-stop / gdb-exit   session lifecycle

Canary matching (per read location, ALL interpretations, any match wins):
  bare register ("$r0")      value == int canary            ("reg-int")
                              buffer at value contains
                              the string canary              ("buf-string")
                              the int canary's byte patterns ("buf-int-*")
  address expression         buffer at the evaluated address
  ("$sp+0x10", "0x9fc00")    is scanned for the string canary and the int
                              canary's 32/64-bit LE/BE patterns
"""

import json
import os
import re
import struct
import time

import gdb

SPEC = json.load(open(os.environ["VPROBE_SPEC"]))
LOG_PATH = os.environ["VPROBE_LOG"]
BRIDGE = os.environ["VPROBE_BRIDGE"]
CANARIES = json.loads(os.environ.get("VPROBE_CANARIES", "{}"))
ARM_MARKER = os.environ.get("VPROBE_ARM_MARKER", "")

PROBES = SPEC.get("probes", [])


def _int_env(name, default):
    try:
        return int(os.environ.get(name) or default)
    except (TypeError, ValueError):
        return default


BUDGET = _int_env("VPROBE_HIT_BUDGET", 2000)
RATE = _int_env("VPROBE_HIT_RATE", 40)
READSZ = _int_env("VPROBE_READSZ", 512)

BARE_REG = re.compile(r"^\$[A-Za-z0-9]+$")


def log(ev):
    ev["t"] = time.time()
    with open(LOG_PATH, "a") as f:
        f.write(json.dumps(ev, ensure_ascii=False) + "\n")


def read_mem(addr, n=READSZ):
    """bytes at addr (b"" when unreadable)."""
    try:
        return gdb.selected_inferior().read_memory(addr, n).tobytes()
    except Exception:
        return b""


def printable(buf, limit=96):
    """printable prefix of a byte buffer, as a str."""
    out = []
    for b in buf[:limit]:
        if b == 0:
            break
        if 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            break
    return "".join(out)


def int_patterns(value):
    """the int canary's byte patterns: 32/64-bit, both endiannesses."""
    out = []
    for tag, fmt in (("le32", "<I"), ("be32", ">I"),
                     ("le64", "<Q"), ("be64", ">Q")):
        out.append((tag, struct.pack(fmt, value)))
    return out


def scan_canaries(pid, buf=None, value=None):
    """(own_probe_matches, foreign_probe_ids) for this buffer/value.

    Only the CHECK'S OWN probe's canary can produce a match — that is the
    proof (this probe's request carried the value to this point). Other
    probes' canaries visible here are cross-contamination, reported as
    diagnostics and never counted. Each match carries the byte offset it
    was found at: 0 = the read location points AT the canary (strong), >0
    = the canary sits deeper in the scanned block (heap-adjacency, weak
    but still this probe's data)."""
    can = CANARIES.get(pid)
    if not isinstance(can, dict):
        return [], []
    matches = []
    s = str(can.get("string", "")).encode()
    iv = can.get("int")
    if buf:
        if s:
            off = buf.find(s)
            if off >= 0:
                matches.append({"mode": "buf-string", "at": off})
        if isinstance(iv, int):
            for tag, pat in int_patterns(iv):
                off = buf.find(pat)
                if off >= 0:
                    matches.append({"mode": "buf-int-" + tag, "at": off})
    if value is not None and isinstance(iv, int) and value == iv:
        matches.append({"mode": "reg-int", "at": None})
    foreign = []
    if buf:
        for opid, oc in CANARIES.items():
            if opid == pid or not isinstance(oc, dict):
                continue
            os_ = str(oc.get("string", "")).encode()
            if os_ and os_ in buf:
                foreign.append(opid)
    return matches, foreign


class BudgetBP(gdb.Breakpoint):
    """canary-less stop budget (see VPROBE_HIT_BUDGET / VPROBE_HIT_RATE).

    Counts consecutive stops that matched no canary of any probe; a
    canary-bearing stop resets the counter. Two trip rules: cumulative
    (BUDGET) and burst (RATE stops within 2s — the loop signature).
    Tripping disables the breakpoint and logs `site_disabled`."""

    def _budget_tick(self, hits, where):
        try:
            if hits:
                self._miss = 0
                self._stamps = []
                return
            if BUDGET <= 0 and RATE <= 0:
                return
            miss = getattr(self, "_miss", 0) + 1
            self._miss = miss
            stamps = getattr(self, "_stamps", None)
            if stamps is None:
                stamps = self._stamps = []
            now = time.time()
            stamps.append(now)
            if RATE > 0:
                if len(stamps) > RATE:
                    stamps.pop(0)
                if len(stamps) == RATE and now - stamps[0] <= 2.0:
                    self._disable(where, "burst")
                    return
            if BUDGET > 0 and miss >= BUDGET:
                self._disable(where, "cumulative")
        except Exception as e:  # budget must never break recording
            log({"event": "error", "where": "budget", "msg": str(e)})

    def _disable(self, where, rule):
        self.enabled = False
        log({"event": "site_disabled", "rule": rule,
             "misses": self._miss, "budget": BUDGET, "rate": RATE, **where})


class CheckBP(BudgetBP):
    """one merged (probe, address) stop: read every location, compare,
    log, auto-continue. `reads` is the union of the read locations of all
    that probe's checks at this address (empty = hit-only/getter stop)."""

    def __init__(self, probe_id, addr_hex, reads):
        super().__init__("*" + addr_hex)
        self.probe_id = probe_id
        self.addr_hex = addr_hex
        self.reads = reads or []

    def stop(self):
        try:
            ev = {"event": "check_stop", "probe": self.probe_id,
                  "break": self.addr_hex, "locations": []}
            matched = []
            foreign_all = []
            for loc in self.reads:
                entry = {"loc": loc}
                try:
                    v = int(gdb.parse_and_eval(loc))
                except Exception as e:
                    entry["error"] = str(e)[:120]
                    ev["locations"].append(entry)
                    continue
                entry["value"] = hex(v)
                buf = read_mem(v)
                if buf:
                    ps = printable(buf)
                    if ps:
                        entry["string"] = ps
                # a bare register: its value is tried as the int canary
                # itself AND as a pointer to a buffer; any other expression
                # is an address — only the block scan applies
                matches, foreign = scan_canaries(
                    self.probe_id, buf=buf,
                    value=v if BARE_REG.match(loc) else None)
                if matches:
                    entry["matches"] = matches
                    matched.extend(m["mode"] for m in matches)
                if foreign:
                    entry["foreign"] = foreign
                    foreign_all.extend(foreign)
                ev["locations"].append(entry)
            ev["matched"] = bool(matched)
            if matched:
                ev["modes"] = sorted(set(matched))
            if foreign_all:
                ev["foreign"] = sorted(set(foreign_all))
            log(ev)
            self._budget_tick(matched or foreign_all,
                              {"probe": self.probe_id, "break": self.addr_hex})
        except Exception as e:  # never break the recording session
            log({"event": "error", "where": "CheckBP.stop", "msg": str(e)})
        return False


def arm_all(phase):
    # merge the probe's checks at the same address into one breakpoint
    # (reads = ordered union); different probes stay separate breakpoints
    groups = {}
    for p in PROBES:
        pid = p.get("id")
        for chk in p.get("checks", []) or []:
            key = (pid, chk.get("break"))
            reads = chk.get("read") or []
            cur = groups.setdefault(key, [])
            for r in reads:
                if r not in cur:
                    cur.append(r)
    armed = 0
    for (pid, addr), reads in groups.items():
        try:
            CheckBP(pid, addr, reads)
            armed += 1
        except Exception as e:
            log({"event": "bp_error", "symbol": addr, "msg": str(e)})
    log({"event": "armed", "phase": phase, "probes": len(PROBES),
         "check_sites": armed, "budget": BUDGET, "rate": RATE,
         "readsz": READSZ})


def main():
    gdb.execute("set confirm off")
    gdb.execute("set pagination off")
    # no symbol file, no architecture guess: the QEMU gdbstub's target
    # description defines the register set; every address comes from the
    # spec, so the recorder needs nothing else
    gdb.execute("target remote %s:1234" % BRIDGE)

    if ARM_MARKER:
        # deferred arming: release the frozen CPU, boot the guest at native
        # speed with NO breakpoints, wait for the driver's SIGINT + marker
        # handshake (web service confirmed up) before arming
        log({"event": "deferred", "marker": ARM_MARKER,
             "budget": BUDGET, "rate": RATE})
        armed_done = False
        while True:
            try:
                gdb.execute("continue")
            except gdb.error as e:
                log({"event": "gdb-exit", "why": str(e)})
                return
            # `continue` returned: the target REALLY stopped (a driver
            # SIGINT; auto-continued breakpoint stops never surface here)
            if not armed_done and os.path.exists(ARM_MARKER):
                arm_all("send-start")
                armed_done = True
            else:
                log({"event": "stray-stop", "armed": armed_done})
            # loop back into `continue` (main() must never return while the
            # session lives: -batch would exit gdb and end the recording)
    else:
        arm_all("boot")
        try:
            gdb.execute("continue")
        except gdb.error as e:
            log({"event": "gdb-exit", "why": str(e)})
            return
    log({"event": "gdb-exit"})


main()
