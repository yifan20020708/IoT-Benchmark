#!/usr/bin/env python3
"""gdb-recorder — GDB-side passive event recorder for verify-request.sh.

Driven entirely by environment variables (set by the driver):
  TPROBE_SPEC     probe specification JSON (see verify-request.sh header)
  TPROBE_LOG      JSONL event log path (appended; flushed per event)
  TPROBE_BRIDGE   <container-bridge-ip> to reach QEMU's gdbstub on :1234
  TPROBE_BINARY   host-side path of the ELF whose symbols/name the bps use
  TPROBE_CANARIES JSON {probe_id: canary} — generated by the driver; the
                  agent never knows these values (anti-fabrication)

A PURE RECORDER: every breakpoint auto-continues (stop() -> False) and
logs an event; the host-side driver owns all timing (web wait, request
sends, teardown, kill). All breakpoints are armed statically BEFORE the
firmware boots (QEMU's -s -S leaves the CPU frozen at reset; QEMU
gdbstub breakpoints are VM-level, so pre-load symbol breakpoints are
safe), then a single `continue` runs until the driver kills gdb.

Event kinds (one JSON object per line, each with a unix timestamp):
  armed        breakpoints armed, architecture detected
  source_hit   taint-source function entered: caller pc (= the call site,
               the return address of that call), argument registers, the
               string each argument points at, canary matches in the
               argument buffers
  entry_hit    entry/handler function entered (dispatch proof)
  ret_hit      return site of a call hit: return register + its string +
               canary matches (the strongest proof: the accessor RETURNED
               attacker data)
  bp_error     a symbol failed to resolve (probe continues without it)
  error        internal recorder error (never fatal to the session)

Register tables cover the corpus architectures (ARM/MIPS/AARCH64); unknown
architectures log a fatal event and leave the log empty.
"""

import json
import os
import re
import time

import gdb

SPEC = json.load(open(os.environ["TPROBE_SPEC"]))
LOG_PATH = os.environ["TPROBE_LOG"]
BRIDGE = os.environ["TPROBE_BRIDGE"]
BINARY = os.environ["TPROBE_BINARY"]
CANARIES = json.loads(os.environ.get("TPROBE_CANARIES", "{}"))

PROBES = SPEC.get("probes", [])
RET_BREAKS = []  # (probe_id, call_site_int) — armed at call + arch delay

ARCH_TABLE = {
    "arm":     {"args": ["$r0", "$r1", "$r2", "$r3"], "ret": "$r0",
                "ret_delay": 4},
    "aarch64": {"args": ["$x0", "$x1", "$x2", "$x3"], "ret": "$x0",
                "ret_delay": 4},
    "mips":    {"args": ["$a0", "$a1", "$a2", "$a3"], "ret": "$v0",
                "ret_delay": 8},
}
ARCH = None


def log(ev):
    ev["t"] = time.time()
    with open(LOG_PATH, "a") as f:
        f.write(json.dumps(ev) + "\n")


def read_mem(addr, n=512):
    """bytes at addr (b"" when unreadable)."""
    try:
        return gdb.selected_inferior().read_memory(addr, n).tobytes()
    except Exception:
        return b""


def c_string(buf, limit=96):
    """printable prefix of a byte buffer, as a str."""
    out = []
    for b in buf[:limit]:
        if b == 0:
            break
        if 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            break
    return "".join(out)


def reg(name):
    try:
        return int(gdb.parse_and_eval(name))
    except Exception:
        return None


def canary_hits(buf):
    return sorted(pid for pid, can in CANARIES.items()
                  if can.encode() in buf)


class SourceBP(gdb.Breakpoint):
    """taint-source or entry function: log the invocation, auto-continue."""

    def __init__(self, symbol, role):
        super().__init__(symbol)
        self.symbol = symbol
        self.role = role  # "source" | "entry"

    def stop(self):
        try:
            ev = {"event": "source_hit" if self.role == "source" else "entry_hit",
                  "symbol": self.symbol, "role": self.role}
            try:
                caller = gdb.newest_frame().older()
                ev["call_site"] = hex(caller.pc()) if caller else None
            except Exception:
                ev["call_site"] = None
            ev["args"] = {}
            ev["arg_strings"] = {}
            ev["canary_hits"] = []
            for r in ARCH["args"]:
                v = reg(r)
                if v is None:
                    continue
                ev["args"][r] = hex(v)
                buf = read_mem(v)
                if buf:
                    s = c_string(buf)
                    if s:
                        ev["arg_strings"][r] = s
                    for pid in canary_hits(buf):
                        if pid not in ev["canary_hits"]:
                            ev["canary_hits"].append(pid)
            log(ev)
        except Exception as e:  # never break the recording session
            log({"event": "error", "where": "SourceBP.stop", "msg": str(e)})
        return False


class RetSiteBP(gdb.Breakpoint):
    """statically-armed return site of a specific call: ret register proof."""

    def __init__(self, probe_id, address):
        super().__init__(address)
        self.probe_id = probe_id

    def stop(self):
        try:
            v = reg(ARCH["ret"])
            ev = {"event": "ret_hit", "probe": self.probe_id,
                  "address": self.location, "ret": hex(v) if v is not None else None}
            if v is not None:
                s = c_string(read_mem(v))
                if s:
                    ev["ret_string"] = s
                    ev["canary_hits"] = canary_hits(s.encode())
                else:
                    ev["canary_hits"] = []
            log(ev)
        except Exception as e:
            log({"event": "error", "where": "RetSiteBP.stop", "msg": str(e)})
        return False


def main():
    global ARCH
    gdb.execute("set confirm off")
    gdb.execute("set pagination off")
    gdb.execute("file " + BINARY)
    gdb.execute("target remote %s:1234" % BRIDGE)

    arch_out = gdb.execute("show architecture", to_string=True)
    arch = None
    for name in ("aarch64", "arm", "mips", "riscv"):
        if name in arch_out:
            arch = name
            break
    if arch not in ARCH_TABLE:
        log({"event": "error", "where": "arch", "msg":
             "unsupported architecture: %r" % arch_out.strip()})
        return
    ARCH = ARCH_TABLE[arch]

    armed = []
    symbols = {p["source_break"]: "source" for p in PROBES if p.get("source_break")}
    for p in PROBES:
        if p.get("entry_break"):
            symbols.setdefault(p["entry_break"], "entry")
    for symbol, role in symbols.items():
        try:
            SourceBP(symbol, role)
            armed.append(symbol)
        except Exception as e:
            log({"event": "bp_error", "symbol": symbol, "msg": str(e)})

    ret_sites = 0
    for p in PROBES:
        for cs in p.get("ret_breaks", []):
            try:
                site = int(cs, 16) + ARCH["ret_delay"]  # call site -> return site
                RetSiteBP(p["id"], "*0x%x" % site)
                ret_sites += 1
            except Exception as e:
                log({"event": "bp_error", "symbol": cs, "msg": str(e)})

    log({"event": "armed", "arch": arch, "symbols": armed,
         "ret_sites": ret_sites, "probes": len(PROBES)})
    gdb.execute("continue")
    # normally unreachable: the driver kills gdb while `continue` runs
    log({"event": "gdb-exit"})


main()
