#!/bin/bash
# agent-scan :: taint — deterministic dynamic verification of taint sources
# (the hverify counterpart of the taint stage)
#
# Usage: verify-request.sh [--keep] [--budget S] [--image IMG] [--out F]
#                          [--workdir D] <model-dir> <spec.json>
#
# Proves, on the harness-verified emulation of a SOLVED task, that network
# request parameters are actually received by the identified intermediate
# taint sources. The agent designs the probes (what to send, where to
# break); this script holds ALL verdict power — the same anti-fabrication
# contract as rehost's hverify:
#   * the CANARY is generated by this script (the agent never sees it) and
#     injected into the request templates as {{CANARY}}
#   * breakpoints are QEMU gdbstub-level, armed before the firmware boots
#   * evidence = the canary appearing in the taint source's argument
#     buffers / the return value of its call — observed by gdb itself
#
# Per run: fresh lab container from the solved image -> emu boot (CPU
# frozen, gdbstub 0.0.0.0:1234) -> host gdb-multiarch attaches over the
# container bridge IP -> web wait -> send each probe's request -> collect
# events -> teardown -> verdicts. One probe batch per boot.
#
# Spec format (agent-authored, JSON):
# {
#   "binary": "rootfs/bin/httpd",        // symbol source, relative to model
#   "probes": [{
#     "id": "setwan-wanType",
#     "request": ["curl","-s","-X","POST","-H","Content-Type: application/json",
#                 "-d","{\"wanType\":\"{{CANARY}}\"}",
#                 "http://{{GUEST_IP}}/goform/module"],
#     "source_break": "cJSON_GetString", // REQUIRED: the taint source fn —
#                                         // a symbol name OR "*0xADDR" (use
#                                         // the address form when the name
#                                         // is ambiguous or stripped)
#     "entry_break": "formSetWanIP",     // optional: dispatch proof (same
#                                         // name-or-*0xADDR forms)
#     "ret_breaks": ["0x48910"],         // optional: CALL-SITE addresses (as
#                                         // printed by taint-query callsites);
#                                         // armed at the return site, where
#                                         // the ret register holds the value
#     "canary_param": "wanType"          // optional: param carrying canary
#   }]
# }
# {{GUEST_IP}} is substituted from the emulation's own IP (emu ip).
# {{CANARY}} (string) and {{CANARY_INT}} (decimal number) are the two canary
# channels, generated per probe by this script and never shown to the
# agent: string params carry the string canary; numeric fields consumed by
# int-returning accessors (cJSON_GetInt/GetBool-style) carry {{CANARY_INT}},
# proven by argument/return register EQUALITY in the recorder. Probes may
# carry "expect": "pass" (default) | "unreachable" | "unfed" — this script
# is expect-blind (exit 1 on any non-pass); the DRIVER interprets expect.
#
# Output: --out verdict JSON (default <model>/taint-source/verify/<stem>/
# verdicts.json) + events.jsonl + gdb.log in the same directory.
# Verdict per probe: pass (canary observed) | no-hit (request never reached
# the source) | no-canary (source ran, canary absent). exit 0 = all pass,
# 1 = any fail, 2 = infrastructure error (boot/attach failure).
set -euo pipefail
export PYTHONDONTWRITEBYTECODE=1   # no __pycache__ anywhere in the pipeline

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
KEEP=0
BUDGET=900          # total wall-clock budget for the whole run
WEBWAIT=300         # max seconds waiting for the web service
EVIDWAIT=120        # max seconds waiting for probe evidence after requests
IMAGE=""
OUT=""
WORKDIR=""
while [ $# -gt 0 ]; do
    case "$1" in
        --keep)    KEEP=1; shift ;;
        --budget)  BUDGET="$2"; shift 2 ;;
        --image)   IMAGE="$2"; shift 2 ;;
        --out)     OUT="$2"; shift 2 ;;
        --workdir) WORKDIR="$2"; shift 2 ;;
        -h|--help) sed -n '2,48p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) break ;;
    esac
done
MODEL="${1:?usage: verify-request.sh [--keep] <model-dir> <spec.json>}"
SPEC="${2:?usage: verify-request.sh [--keep] <model-dir> <spec.json>}"
MODEL="$(cd "$MODEL" 2>/dev/null && pwd)" || { echo "[-] no such dir: $1" >&2; exit 2; }
[ -f "$MODEL/task.json" ] || { echo "[-] not a model dir (no task.json): $MODEL" >&2; exit 2; }
[ -f "$SPEC" ] || { echo "[-] no such spec: $SPEC" >&2; exit 2; }
SPEC="$(readlink -f "$SPEC")"
STEM="$(basename "$SPEC" .json)"

VENDOR=$(basename "$(dirname "$MODEL")")
MODELNAME=$(basename "$MODEL")
TASK_ID=$(printf '%s__%s' "$VENDOR" "$MODELNAME" | tr '[:upper:]' '[:lower:]' | sed 's/[^a-z0-9._-]/-/g')
IMAGE="${IMAGE:-task-$TASK_ID:solved}"
# container name carries the spec stem: concurrent runs of different specs
# (parallel batch splits, driver re-run next to agent self-checks) each get
# their own container instead of docker rm -f'ing each other
CONTAINER="taint-verify-$TASK_ID-$(printf '%s' "$STEM" | tr '[:upper:]' '[:lower:]' | sed 's/[^a-z0-9._-]/-/g')"
# --workdir overrides the default work dir (taint-source/verify/<stem>):
# batch drivers (verify-batch.sh) keep their per-chunk artifacts together
WORK="${WORKDIR:-$MODEL/taint-source/verify/$STEM}"
mkdir -p "$WORK"

RUN_START=$(date +%s)
teardown() {
    # gdb: TERM then KILL; emulation: emu stop; container: rm unless --keep
    if [ -n "${GDBPID:-}" ] && kill -0 "$GDBPID" 2>/dev/null; then
        kill -TERM "$GDBPID" 2>/dev/null || true
        sleep 3
        kill -KILL "$GDBPID" 2>/dev/null || true
    fi
    docker exec "$CONTAINER" emu stop >/dev/null 2>&1 || true
    if [ "$KEEP" = 1 ]; then
        echo "[*] container kept for inspection: $CONTAINER"
    else
        docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
    fi
}
trap 'teardown; trap - EXIT' EXIT

# ---- validate the spec and generate canaries -------------------------------
python3 - "$SPEC" "$WORK" <<'EOF'
import json, os, secrets, sys
spec, work = sys.argv[1:3]
try:
    s = json.load(open(spec))
except Exception as e:
    sys.exit(f"[-] spec is not valid JSON: {e}")
probes = s.get("probes")
if not isinstance(probes, list) or not probes:
    sys.exit("[-] spec must hold a non-empty 'probes' list")
ids = set()
for i, p in enumerate(probes):
    for k in ("id", "request", "source_break"):
        if not p.get(k):
            sys.exit(f"[-] probe[{i}] missing field: {k}")
    if not isinstance(p["request"], list) or not all(isinstance(a, str) for a in p["request"]):
        sys.exit(f"[-] probe[{i}].request must be a list of strings")
    if p["id"] in ids:
        sys.exit(f"[-] duplicate probe id: {p['id']}")
    ids.add(p["id"])
    if p.get("expect") not in (None, "pass", "unreachable", "unfed"):
        sys.exit(f"[-] probe[{i}]: 'expect' must be 'pass', 'unreachable' or "
                 f"'unfed', got {p.get('expect')!r}")
# canaries are generated HERE, never shown to the caller: the agent cannot
# pre-plant evidence for a value it has not seen. Two channels per probe:
# the string canary (arg/return buffers) and the int canary (register
# equality — int-returning accessors can never surface a string)
canaries = {p["id"]: {"string": "TAINT-" + secrets.token_hex(5),
                      "int": secrets.randbits(31)} for p in probes}
json.dump(canaries, open(os.path.join(work, "canaries.json"), "w"), indent=2)
print(f"[verify] spec ok: {len(probes)} probe(s)")
EOF

BINARY_REL=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("binary",""))' "$SPEC")
[ -n "$BINARY_REL" ] || { echo "[-] spec must define binary (relative to model dir)" >&2; exit 2; }
BINARY="$MODEL/$BINARY_REL"
[ -f "$BINARY" ] || { echo "[-] binary not found: $BINARY" >&2; exit 2; }
command -v gdb-multiarch >/dev/null || { echo "[-] gdb-multiarch missing on host (apt install gdb-multiarch)" >&2; exit 2; }
docker image inspect "$IMAGE" >/dev/null 2>&1 || { echo "[-] no such image: $IMAGE" >&2; exit 2; }

# ---- fresh lab container + frozen gdb boot ---------------------------------
echo "[verify] task=$TASK_ID image=$IMAGE container=$CONTAINER"
docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
docker run -d --init --privileged --device /dev/kvm -v /dev:/dev \
    --entrypoint /usr/local/bin/emu-shell \
    --name "$CONTAINER" "$IMAGE" >/dev/null || { echo "[-] docker run failed" >&2; exit 2; }

for _ in $(seq 1 30); do
    docker exec "$CONTAINER" pg_isready -q -h 127.0.0.1 && break
    sleep 1
done
docker exec "$CONTAINER" pg_isready -q -h 127.0.0.1 || { echo "[-] PostgreSQL failed" >&2; exit 2; }

echo "[verify] emu boot (CPU frozen, gdbstub :1234)..."
docker exec "$CONTAINER" emu boot || { echo "[-] emu boot failed" >&2; exit 2; }

BRIDGE=$(docker inspect -f '{{.NetworkSettings.IPAddress}}' "$CONTAINER")
GUEST_IP=$(docker exec "$CONTAINER" emu ip 2>/dev/null | head -1)
[ -n "$GUEST_IP" ] || { echo "[-] no guest IP (emu ip)" >&2; exit 2; }
echo "[verify] bridge=$BRIDGE guest=$GUEST_IP"
timeout 5 bash -c "</dev/tcp/$BRIDGE/1234" 2>/dev/null \
    || { echo "[-] gdbstub unreachable at $BRIDGE:1234" >&2; exit 2; }

# ---- arm the recorder (breakpoints before boot) and release the VM ---------
: > "$WORK/events.jsonl"   # fresh log per run (recorder appends)
GDBPID=""
TPROBE_SPEC="$SPEC" \
TPROBE_LOG="$WORK/events.jsonl" \
TPROBE_BRIDGE="$BRIDGE" \
TPROBE_BINARY="$BINARY" \
TPROBE_CANARIES="$(cat "$WORK/canaries.json")" \
gdb-multiarch -batch -nx -q -x "$ROOT/scripts/taint/gdb-recorder.py" \
    >"$WORK/gdb.log" 2>&1 &
GDBPID=$!
echo "[verify] gdb recorder pid=$GDBPID (breakpoints armed at reset)"

# ---- wait for the web service -----------------------------------------------
# BUDGET caps the WHOLE run (boot + web wait + probes + evidence): each wait
# phase takes at most the remaining budget, never its nominal maximum
deadline=$(( RUN_START + BUDGET ))
remain=$(( deadline - $(date +%s) ))
[ "$remain" -gt 0 ] || remain=5
[ "$remain" -gt "$WEBWAIT" ] && remain=$WEBWAIT
echo "[verify] waiting for web at http://$GUEST_IP/ (max ${remain}s)..."
web_code=000
for _ in $(seq 1 $(( remain / 5 ))); do
    # NOTE: curl -w prints the code itself on failure too ("000", rc != 0);
    # only default when it printed nothing at all
    web_code=$(docker exec "$CONTAINER" curl -s -o /dev/null -w '%{http_code}' \
        --max-time 5 "http://$GUEST_IP/" 2>/dev/null || true)
    [ -n "$web_code" ] || web_code=000
    [ "$web_code" != "000" ] && break
    kill -0 "$GDBPID" 2>/dev/null || break
    sleep 5
done
if [ "$web_code" = "000" ] || [ -z "$web_code" ]; then
    echo "[-] web service never answered (last code: $web_code)" >&2
    echo "false" > "$WORK/web_ready"
else
    echo "true" > "$WORK/web_ready"
    echo "[verify] web answering (HTTP $web_code) — sending probes"
fi

# ---- send the probes ---------------------------------------------------------
# the send loop is also budget-capped now: a batch driver re-runs skipped
# probes in its repair round, so a wedged tail cannot burn unbounded time
python3 - "$SPEC" "$WORK" "$CONTAINER" "$GUEST_IP" "$deadline" <<'EOF'
import json, os, subprocess, sys, time
spec, work, ctr, guest_ip = sys.argv[1:5]
deadline = float(sys.argv[5]) if len(sys.argv) > 5 and sys.argv[5] else 0.0
spec = json.load(open(spec))
canaries = json.load(open(os.path.join(work, "canaries.json")))
sends = {}
for p in spec["probes"]:
    can = canaries[p["id"]]
    if deadline and time.time() > deadline:
        sends[p["id"]] = {"skipped": "budget"}
        print(f"[verify] probe {p['id']}: SKIPPED (budget exhausted)")
        continue
    argv = [a.replace("{{GUEST_IP}}", guest_ip)
             .replace("{{CANARY}}", can["string"])
             .replace("{{CANARY_INT}}", str(can["int"]))
            for a in p["request"]]
    print(f"[verify] probe {p['id']}: {' '.join(argv[:6])}{' ...' if len(argv) > 6 else ''}")
    t0 = time.time()
    rc = subprocess.run(["docker", "exec", ctr] + argv,
                        capture_output=True, text=True, timeout=60).returncode
    sends[p["id"]] = {"t": t0, "curl_rc": rc}
    time.sleep(2)  # let the handler run before the next request
json.dump(sends, open(os.path.join(work, "send-times.json"), "w"), indent=2)
EOF

# ---- wait for evidence --------------------------------------------------------
remain=$(( deadline - $(date +%s) ))
[ "$remain" -gt 0 ] || remain=10
[ "$remain" -gt "$EVIDWAIT" ] && remain=$EVIDWAIT
echo "[verify] collecting evidence (max ${remain}s)..."
for _ in $(seq 1 $(( remain / 5 ))); do
    python3 - "$SPEC" "$WORK" <<'EOF' && break || true
import json, os, sys
spec = json.load(open(sys.argv[1]))
work = sys.argv[2]
want = {p["id"] for p in spec["probes"]}
events = [json.loads(l) for l in open(os.path.join(work, "events.jsonl"))
          if l.strip()] if os.path.exists(os.path.join(work, "events.jsonl")) else []
got = {e.get("probe") for e in events if e.get("event") == "ret_hit" and e.get("canary_hits")}
got |= {pid for e in events if e.get("event") == "source_hit"
        for pid in e.get("canary_hits", [])}
sys.exit(0 if want <= got else 1)
EOF
    kill -0 "$GDBPID" 2>/dev/null || break
    sleep 5
done

# ---- verdict -------------------------------------------------------------------
OUT="${OUT:-$WORK/verdicts.json}"
VERDICT_RC=0
python3 - "$SPEC" "$WORK" "$OUT" <<'EOF' || VERDICT_RC=$?
import json, os, sys
spec_path = sys.argv[1]
spec = json.load(open(spec_path))
work, outp = sys.argv[2:4]
sends = json.load(open(os.path.join(work, "send-times.json")))
events = []
evp = os.path.join(work, "events.jsonl")
if os.path.exists(evp):
    events = [json.loads(l) for l in open(evp) if l.strip()]

results = []
all_pass = True
for p in spec["probes"]:
    pid = p["id"]
    src = [e for e in events if e.get("event") == "source_hit"
           and e.get("symbol") == p["source_break"]]
    hit = [e for e in src if pid in e.get("canary_hits", [])]
    ret = [e for e in events if e.get("event") == "ret_hit"
           and e.get("probe") == pid and pid in e.get("canary_hits", [])]
    entry = []
    if p.get("entry_break"):
        t0 = sends.get(pid, {}).get("t", 0)
        entry = [e for e in events if e.get("event") == "entry_hit"
                 and e.get("symbol") == p["entry_break"]
                 and abs(e.get("t", 0) - t0) <= 60]
    # param-name proof: a canary-bearing return whose call site also shows the
    # parameter name in the source's argument registers
    def norm_site(s):
        return str(s).lstrip("*").removeprefix("0x").lower()
    ret_sites = {norm_site(e.get("address")) for e in ret}
    named = bool(p.get("canary_param")) and any(
        p["canary_param"] in (e.get("arg_strings") or {}).values()
        for e in src if norm_site(e.get("call_site")) in ret_sites)
    if hit or ret:
        verdict = "pass"
    elif src:
        verdict = "no-canary"
    else:
        verdict = "no-hit"
        all_pass = False
    if verdict != "pass":
        all_pass = False
    results.append({
        "probe": pid, "verdict": verdict,
        "canary_param_match": named,
        "source_symbol": p["source_break"],
        "source_hits": len(src),
        "canary_evidence": [
            {"call_site": e.get("call_site"), "arg_strings": e.get("arg_strings")}
            for e in hit[:5]],
        "return_evidence": [
            {"call_site": e.get("address"), "ret": e.get("ret"),
             "ret_string": e.get("ret_string")}
            for e in ret[:5]],
        "entry_hits": len(entry),
        "entry_verified": bool(entry),
        "request_sent_at": sends.get(pid, {}).get("t"),
    })

res = {
    "spec": os.path.basename(spec_path),
    "all_pass": all_pass,
    "web_ready": open(os.path.join(work, "web_ready")).read().strip() == "true",
    "probes": results,
}
json.dump(res, open(outp, "w"), indent=2, ensure_ascii=False)
print(f"[verify] verdicts -> {outp}")
for r in results:
    mark = "PASS" if r["verdict"] == "pass" else r["verdict"].upper()
    print(f"  {mark:10s} {r['probe']:28s} "
          f"src_hits={r['source_hits']} entry={'Y' if r['entry_verified'] else '-'}")
sys.exit(0 if all_pass else 1)
EOF

echo "[verify] done in $(( $(date +%s) - RUN_START ))s (events: $WORK/events.jsonl)"
[ "$VERDICT_RC" = 0 ] && exit 0 || exit "$VERDICT_RC"
